import { describe, expect, test } from "bun:test"
import { mkdir, mkdtemp, readFile, rm, symlink, writeFile } from "node:fs/promises"
import { tmpdir } from "node:os"
import { join } from "node:path"
import {
  ASSET_DEFINITIONS,
  assetTexts,
  generateWorkflowBundle,
  PACKAGE_ROOT,
} from "../../scripts/public/workflow-assets.ts"
import { assetHash, serializeAssetBundle } from "../../src/workflow/asset-bundle.ts"
import { everyText } from "../../src/workflow/assets.ts"
import { MOD_FILES } from "../../src/workflow/mod-files.ts"

describe("canonical workflow source composition", () => {
  test("matches every current phase, helper, schema, template and skill byte", async () => {
    const bundle = await generateWorkflowBundle("13.1.0")
    const texts = assetTexts(bundle)
    const current = everyText()
    const currentIds = Object.keys(texts).filter(
      (id) => !id.startsWith("native:") && !id.startsWith("bootstrap:"),
    )
    expect(currentIds.sort()).toEqual(Object.keys(current).sort())
    for (const [id, text] of Object.entries(current))
      expect(assetHash(texts[id as keyof typeof texts] as string)).toBe(assetHash(text))
    for (const asset of bundle.assets)
      for (const source of asset.sources) {
        expect(assetHash(await readFile(join(PACKAGE_ROOT, source.path), "utf8"))).toBe(
          source.sha256,
        )
        expect(bundle.composition.find((entry) => entry.path === source.path)?.sha256).toBe(
          source.sha256,
        )
      }
  })

  test("accounts for all declared native and mod installation inputs without modifying them", async () => {
    const texts = assetTexts(await generateWorkflowBundle("13.1.0"))
    for (const file of MOD_FILES)
      expect(assetHash(texts[`bootstrap:mod/${file.path}`] as string)).toBe(assetHash(file.text))
    for (const name of ["pi.ts.tmpl", "opencode.ts.tmpl", "peers.js.tmpl"])
      expect(assetHash(texts[`native:${name}`] as string)).toBe(
        assetHash(await readFile(join(PACKAGE_ROOT, "src/workflow/native", name), "utf8")),
      )
  })

  test("includes every phase/schema/template/skill source and has stable repeated output", async () => {
    const inputs = new Set(ASSET_DEFINITIONS.flatMap((entry) => entry.sources))
    for (const glob of [
      "src/workflow/phases/*.md",
      "src/workflow/schemas/*.json",
      "src/workflow/artifacts/*.tmpl",
      "src/skills/*/SKILL.md",
    ])
      for await (const path of new Bun.Glob(glob).scan({ cwd: PACKAGE_ROOT }))
        expect(inputs.has(path)).toBe(true)
    const first = await generateWorkflowBundle("13.1.0")
    expect(assetHash(serializeAssetBundle(await generateWorkflowBundle("13.1.0")))).toBe(
      assetHash(serializeAssetBundle(first)),
    )
    const composers = new Set(first.composition.map((source) => source.path))
    for (const path of [
      "src/core/briefs.ts",
      "src/core/instructions.ts",
      "src/core/platform.ts",
      "src/core/shell.ts",
      "src/core/task/question-batch.ts",
      "src/task-memory.ts",
      "src/ui/agent-window/conversation/context-draft.ts",
      "src/core/need/need.ts",
      "src/core/judge-environment.ts",
      "src/core/git/build-start.ts",
      "src/core/task/chat-questions.ts",
    ])
      expect(composers.has(path)).toBe(true)
    expect([...composers].some((path) => path.startsWith("src/core/licence/"))).toBe(false)
    expect([...composers].some((path) => path.startsWith("src/commercial/licensing/"))).toBe(false)
    for await (const path of new Bun.Glob("src/core/handoff/*.ts").scan({ cwd: PACKAGE_ROOT }))
      expect(composers.has(path)).toBe(true)
  })

  test("binds omitted and newly nested public producers while excluding private/generated bytes", async () => {
    const scratch = await mkdtemp(join(tmpdir(), "ql-producer-closure-"))
    try {
      const original = await generateWorkflowBundle("13.1.0")
      const paths = new Set([
        ...original.assets.flatMap((asset) => asset.sources.map((source) => source.path)),
        ...original.composition.map((source) => source.path),
      ])
      for (const path of paths) {
        await mkdir(join(scratch, path, ".."), { recursive: true })
        await writeFile(join(scratch, path), await readFile(join(PACKAGE_ROOT, path)))
      }
      const write = async (path: string, text: string) => {
        await mkdir(join(scratch, path, ".."), { recursive: true })
        await writeFile(join(scratch, path), text)
      }
      for (const path of [
        "src/core/licence/private.ts",
        "src/commercial/licensing/private.ts",
        "src/server/ui/generated.ts",
        "src/memory-engine/payloads/manifest.json",
      ])
        await write(path, "private generated bytes")
      expect((await generateWorkflowBundle("13.1.0", scratch)).digest).toBe(original.digest)
      for (const path of [
        "src/core/need/need.ts",
        "src/core/judge-environment.ts",
        "src/core/git/build-start.ts",
        "src/core/task/chat-questions.ts",
      ]) {
        const text = await readFile(join(scratch, path), "utf8")
        await write(path, `${text}\n// Changed instruction producer.\n`)
        expect((await generateWorkflowBundle("13.1.0", scratch)).digest).not.toBe(original.digest)
        await write(path, text)
      }
      await write(
        "src/core/future/nested/deeper/producer.ts",
        'export const instruction = "A new instruction"\n',
      )
      const expanded = await generateWorkflowBundle("13.1.0", scratch)
      expect(
        expanded.composition.some(
          (entry) => entry.path === "src/core/future/nested/deeper/producer.ts",
        ),
      ).toBe(true)
      expect(expanded.digest).not.toBe(original.digest)
      expect(expanded.composition.some((entry) => entry.path.includes("/licence/"))).toBe(false)
      await write(
        "src/core/future/nested/deeper/instructions.rules",
        "An additional instruction input.\n",
      )
      const extraInput = await generateWorkflowBundle("13.1.0", scratch)
      expect(extraInput.digest).not.toBe(expanded.digest)
      expect(
        extraInput.composition.some((entry) => entry.path.endsWith("instructions.rules")),
      ).toBe(true)
      for (const witness of extraInput.composition)
        expect(Object.keys(witness).sort()).toEqual(["path", "sha256"])
    } finally {
      await rm(scratch, { recursive: true, force: true })
    }
  })

  test("refuses absent inputs and a symlink to a source outside the selected tree", async () => {
    const scratch = await mkdtemp(join(tmpdir(), "ql-public-assets-"))
    try {
      const root = join(scratch, "root")
      await mkdir(join(root, "src/workflow/phases"), { recursive: true })
      await expect(generateWorkflowBundle("13.1.0", root)).rejects.toThrow()
      await symlink(
        join(PACKAGE_ROOT, "src/workflow/phases/artifact-authoring.md"),
        join(root, "src/workflow/phases/artifact-authoring.md"),
      )
      await expect(generateWorkflowBundle("13.1.0", root)).rejects.toThrow("escapes package")
    } finally {
      await rm(scratch, { recursive: true, force: true })
    }
  })
})
